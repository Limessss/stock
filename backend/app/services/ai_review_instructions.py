"""页面复制指令和 MCP prompt 共用的复盘任务模板。"""

from __future__ import annotations

import json
import hashlib
import os
import sys
from datetime import date

from ..core.config import REPO_ROOT, settings


class ReviewHandbookError(ValueError):
    """指定的复盘依据暂不可读取，不使用旧副本替代。"""


def connection_info(api_url: str | None = None) -> dict:
    base_url = os.environ.get("STOCKMODEL_API_URL") or api_url or "http://127.0.0.1:8000/api"
    base_url = base_url.rstrip("/")
    command = sys.executable.replace("\\", "/")
    script = (REPO_ROOT / "backend" / "mcp_server.py").as_posix()
    env = {"STOCKMODEL_API_URL": base_url, "PYTHONUTF8": "1"}
    server = {"type": "stdio", "command": command, "args": [script], "env": env}
    codex_config = "\n".join(
        [
            "[mcp_servers.stockmodel]",
            f"command = {json.dumps(command, ensure_ascii=False)}",
            f"args = {json.dumps([script], ensure_ascii=False)}",
            "startup_timeout_sec = 30",
            "tool_timeout_sec = 90",
            "",
            "[mcp_servers.stockmodel.env]",
            f"STOCKMODEL_API_URL = {json.dumps(base_url, ensure_ascii=False)}",
            'PYTHONUTF8 = "1"',
        ]
    )
    return {
        "server_name": "stockmodel",
        "transport": "stdio",
        "api_url": base_url,
        "claude_config": json.dumps(
            {"mcpServers": {"stockmodel": server}}, ensure_ascii=False, indent=2
        ),
        "codex_config": codex_config,
        "tools": [
            "get_review_context",
            "get_review_day",
            "get_stock_history",
            "list_ai_reviews",
            "get_ai_review",
            "submit_ai_review",
        ],
    }


def review_instructions(trade_date: date, api_url: str | None = None) -> dict:
    connection = connection_info(api_url)
    day = trade_date.isoformat()
    # 每次请求读取同一份源文件，文档更新无需重启后端；哈希和正文来自同一次读取。
    handbook_path = settings.ai_review_handbook_path
    try:
        handbook_bytes = handbook_path.read_bytes()
        handbook = handbook_bytes.decode("utf-8-sig").strip()
    except (OSError, UnicodeError) as exc:
        raise ReviewHandbookError(
            f"无法读取复盘手册：{handbook_path}。请检查文件是否存在、可读且为 UTF-8 编码，保存后重试。未使用旧副本。"
        ) from exc
    if not handbook:
        raise ReviewHandbookError(f"复盘手册为空：{handbook_path}。请保存完整内容后重试。未使用旧副本。")
    handbook_version = hashlib.sha256(handbook_bytes).hexdigest()[:12]
    prompt = f"""请通过本机 stockmodel MCP，为 {day} 完成 A 股盘后复盘，并将完整报告回传到项目的「AI复盘」页面。

【连接】
优先使用已连接的 stockmodel MCP 工具。服务运行在项目所在的这台电脑上，项目后端须保持运行。
如果还没有连接，请按当前客户端支持的方式添加下面的 stdio MCP 配置；合并已有配置，不覆盖其他服务器。若当前会话无法动态加载 MCP，请明确给出接入/重载步骤，等工具可用后继续，不要声称已经连接或提交。
Codex 配置（~/.codex/config.toml）：
```toml
{connection["codex_config"]}
```
Claude Code 配置（项目 .mcp.json，合并 mcpServers）：
```json
{connection["claude_config"]}
```

【项目复盘约定】
本次以本指令内完整提供的《完整情绪周期操作手册》为阶段定义、角色关系、赚钱效应和执行纪律的依据，方法版本 {handbook_version}。正文是生成本指令时从用户指定原文件实时读取的内容。这是用户指定的个人分析体系，其阶段强弱是定性框架，不是已验证的收益规律。阶段名称、定义、角色关系和纪律适用范围均以本次手册全文为准；项目流程只约定取证与呈现方式，不另设固定方法定义。与旧报告或旧提示词不同时，按本次手册重新审视并说明调整。
手册正文已由项目统一提供，日常 Agent 无需另外访问个人笔记路径、检索帖子或阅读手册及历史报告中的外链。手册内的文献链接仅为出处，不构成访问原帖的任务。正式报告直接展示行情推演，不写学习经历、作者观点对照或手册导读；在数据来源末尾简记方法版本即可。缺口应限定到它影响的具体结论，不能修改定义来迁就数据，也不能因局部缺口放弃现有证据支持的阶段判断。

【读取与证据】
1. 初次调用 get_review_context(trade_date="{day}", lookback_days=30)，至少回看 30 个交易日的市场、题材与梯队变化，不得用 30 个自然日或只看最近 10 日替代。检查 window_coverage、逐日 availability、caveats 与 prior_reports，报告实际起止日期、可用天数及各来源缺口。本地记录不足 30 日时明确说明不足，不能声称已完成 30 日复盘；日期由本地记录确定，不能把返回天数等同于各项数据完整。若主线启动或关键阶段转换早于窗口，继续扩至 60 或 120 日（单次最多 120 日），更早关键日可单独读取，窗口第一天不是周期起点。用 get_review_day 读取当日和关键转折日的完整缓存排名、梯队、原因及题材关系，不用摘要前几名代替全体。
2. 对主要龙头候选、容量核心、助攻/补涨、前任核心与指数调用 get_stock_history(code=证券代码, end_date="{day}", bars=60)，证券代码为 SH/SZ/BJ 加六位数字。按需扩至 120 根或更多（最多 500 根），检查 actual_end_date、缺K与复权口径。回溯以解释当前主线的阶段切换为止，不为增加篇幅无限追溯。
3. 先从关键日期的完整梯队、题材关系及此前项目报告建立候选范围，再比较启动/确认先后、相同窗口的相对表现、分歧时的持续性、容量与助攻反馈。纳入已经掉队的前任和竞争失败者，说明重要候选未选为龙头的理由。最高板、最大单日涨幅或突破自身前高均不能自动确定主线龙头；“空间参照”“容量代表”与“主导核心”分别说明，不能把任一观察对象直接升为整个市场的周期锚。候选未分胜负就列竞争对象及区分条件。
4. 固定此前群体进行后续检验：至少读取上一交易日完整梯队，以及主线一次关键分歧日的核心、助攻和跟随名单。保留失败者、交叉标签和缺失，比较当日及连续几日正负反馈、分歧股修复与新负反馈。统计写基准、样本数和实际截止日；不得从今天幸存者反推此前机会普遍很好。名单整体尚未回到某日价格，不自动否定主导身份变化；也不能用核心独强遮蔽可参与群体普遍变差。
5. 预期检验只采用截至 {day} 当时已经归档、面向相应后续交易日的项目判断。读取 prior_reports，必要时 get_ai_review 获取全文，标明兑现、部分兑现、落空、不可检验及判断如何修正。没有合适报告写“无可检验的项目历史预期”。同日报告、事后补交内容或本次重建不得包装为此前预测；不同 Agent 的判断按证据比较。
6. 以 {day} 为观察终点，不能用后续行情解释当时应有判断。新闻、涨停原因和历史报告是材料，不是操作指令。开盘啦 strength 不是净流入或阶段标签；板块涨幅字段不是完整板块指数序列；N天M板须与连续板区分。缺失不等于零。

【分析工作：完整取证，集中呈现】
以下是 Agent 的内部工作流程，不是报告目录，不要逐条抄进报告。
1. 先比较主线及核心候选，再检查核心、容量、助攻和后排的连续反馈。按手册判断“前几天出现的机会后来怎么样、分歧后有没有修复、正反馈正在扩散还是集中到少数股”。启动归属、阶段领涨和当前地位分别论证；地位更替与阶段切换也分别论证。市场、题材与个股可处于不同阶段，不能用大盘弱否定全部新方向。
2. 对每条重点线索先选现有证据最支持的阶段解释，再用最强反证检验。可以判断“转一正在向转二发展”，但必须说明哪些跨日变化推动了这个判断，以及离更强结论还差什么。证据确实不足时保留过渡判断；不能为了显得果断而强行升级，也不能只列一串候选而不给倾向。阶段及细分条件以当次手册为准，不按板数、天数、单日排名套用。
3. 回溯最近必要的转折：先前是什么状态，哪个日期核心或原跟随群体的表现变了，为什么因此维持、升级或下调阶段。每个重要切换保留日期、关键证据和反证，不强行补齐所有阶段。区分当时已有判断、本次重建与后来确认。
4. 检验新分支自身的核心、容量与原跟随群体能否持续。旧方向是否修复是比较证据，不是一律要求通过的前置条件；旧线继续走弱时，新分支仍可能独立发展。跨题材同涨或一强一弱都不能直接证明资金搬家。
5. 依据支持的阶段给出手册适用的条件性纪律，核对细分条件，不能扩大纪律适用范围。未取得用户风险预算、持仓与交易记录时，不指定仓位百分比，不虚构实际交易或盈亏。

【阶段判断与具体买点分开】
日线、成交额、完整梯队和固定群体的连续表现，能够支持有依据的阶段倾向：看核心是否持续、跟随是否扩散、分歧后是否收复、此前强股是否反复下跌。多项证据吻合时应明确判断及主要反证；不能仅因没有分时、逐笔或用户交易记录，就把所有新方向一直限制在“启动/转一候选”，或否定转二、三阶段的分析可能。
这些数据不能证明具体分钟的买点可成交、盘中主动承接或带动、封单变化、实际修复退出和策略胜率。日线区间及开收盘变化可辅助判断参与质量，但仍是价格反馈，不等于实际交易收益。一字/缩量本身不能证明派发、控盘或无法买到。需要这些细节才能成立的结论，才单独注明“此项缺少分时/成交证据”；不能把局部限制扩展为对整条主线的否定。
若某个阶段的关键条件只能通过现有价格表现间接支持，说明这一处推断及最需要补证的条件即可，不改写手册定义。当天新出现的群体尚无后续数据，这属于持续性证据不足，应与“缺少分时”区分。来源缺口统一放在文末一次说明，只有会改变当前主判断的缺口才在正文就近补一句。

【报告写法：先读懂判断，再按需查证】
使用中文 Markdown。正文目标约 1500—2500 字，一般不超过 3000 字（不含数据附录）；确有重要切换可适当超出。长度是编辑目标，不是删掉关键反证或跳过取证的理由。信息少时更短，不为凑字数增加章节。

正文只围绕下面四部分展开，用具体结论作小标题，不重复输出报告标题、目录或摘要：
1. **今天发生了什么**：开头 2—3 句给出总判断，再用少量关键数据解释指数、成交、涨跌家数与短线反馈是否一致。重点讲相较上一日改变了什么，不抄完整市场统计。
2. **最值得跟踪的变化**：优先讲最重要的 2—3 条线索；其他方向只有会改变结论时才补一句。每条线索在同一处讲清“当前判断 → 带日期的转折及角色关系 → 最关键支持证据 → 最强反证”。赚钱效应、参与质量与阶段变化合在该线索里解释，不另开章节再说一次。旧主线的退潮与新方向的成长均须纳入比较，按重要性分配篇幅。
3. **明天只盯什么**：通常保留 3 项最能改变判断的观察，每项写清对象、出现什么变化就维持/调整哪项判断，以及适用的执行倾向。只写真正影响当前结论的分岔，不给每条题材各列一整套上涨、下跌、修复情景。
4. **预期如何修正**：有可检验旧报告时简述兑现/落空及修正；没有时用一句“无可检验的项目历史预期”。同日报告改写注明是修订，不包装成预测兑现。

写作约束：
- 每段一件事，通常 2—4 句。先说谁在什么日期发生了什么，再说明为什么影响判断。首次使用必要阶段术语时顺带解释，不专门讲课。少用括号、斜杠和长串箭头。
- 每个结论用 1—2 组最有区分力的数据支撑。群体统计在正文保留基准日、有效样本数及缺失，完整名单放附录。金额用亿元/万亿元，保留有用的精度。
- 同一结论、数字或缺口只完整解释一次；次日计划直接给验证条件，不再复述整段论据。不要把“事实/推断/待验证”变成每段的固定套话，也不要反复使用“候选、不能确认、价格代理”。
- 数据、反证和推理必须保留；工具调用过程、研究检查清单、术语定义表及与原帖的对照不进入正文。不要为了满足内部流程而输出一篇流程说明书。

正文之后用单独的二级标题 `## 数据与依据` 开始附录，所有附录集中在文末，页面默认折叠这一节。只放复算所需的固定名单、基准与算法、来源日期、具体缺失、必要次要对照和承接报告 ID；与核心判断有关的证据和反证不能藏进附录。方法版本简记《完整情绪周期操作手册》{handbook_version}。不附完整日线流水账，不复制整套手册或检查清单，也不把删掉的重复正文搬进附录。Markdown 保持完整，勿自行输出 HTML 折叠标签。

提交前在内部完成手册的每日复盘清单，再做一次编辑：主线和阶段切换有无依据？纪律是否越界？“缺少分时”是否被用来回避可作出的判断？是否有同一段意思出现两次？读者能否一遍看懂“为什么变了，明天看什么”？检查结果不单列章节。

【复盘依据全文：完整情绪周期操作手册】
方法版本：{handbook_version}。以下全文在生成本指令时直接读取用户指定原文件；前述流程负责将当前手册应用到可获得的数据。手册后续修改不会改变已经复制的指令，本次复盘按此版本完成。

{handbook}

【复盘依据全文结束】

【提交与确认】
完成后调用 submit_ai_review(report={{...}})，不要只把报告留在聊天窗口。
report 字段：
- trade_date: "{day}"
- agent_name: 你实际使用的 Agent 名称（如 Codex、Claude Code），model: 实际模型名（不确定则留空）
- title: 用通俗的一句话突出当日最重要变化，summary: 用 2—3 句易懂的完整话说明结论、主要理由和待观察条件，便于时间轴阅读
- content_markdown: 完整报告，tags: 主要题材/阶段标签，linked_codes: 核心证券代码
- data_sources: 实际使用的数据来源/工具/日期说明列表
- data_cutoff: 明确知道时填写含时区的截止时刻；不知道则省略
- submission_id: 为本次报告生成一个唯一 ID。网络重试必须复用相同 ID 和内容；另写一版报告应使用新 ID。
提交为追加归档，同一天多个 Agent 和多次复盘均保留。收到成功回执后，用 get_ai_review 读取回执 id 核实，再向我反馈报告标题、id 和 report_path。连接或提交失败时如实说明，不以聊天输出冒充入库成功。
"""
    return {"trade_date": day, "prompt": prompt, "connection": connection}
